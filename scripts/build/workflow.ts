/**
 * Compile the TypeScript entry point into the JavaScript Pi executes.
 * The literal metadata header is read by pi-subagents before it starts the VM.
 */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../../", import.meta.url));
const entryPoint = `${root}/src/review/workflow.ts`;
const entrySource = await readFile(entryPoint, "utf8");
// Copy the formatted literal declaration: Pi reads it before running the bundle.
const metadata = entrySource.match(/^export const meta = \{[\s\S]*?^\};/m)?.[0];
if (!metadata) {
  throw new Error("Workflow must declare literal metadata");
}
const output = await build({
  entryPoints: [entryPoint],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "ReviewWorkflow",
  target: "es2023",
  minify: true,
  legalComments: "none",
  loader: { ".md": "text" },
});
const source = `// Generated by npm run build from src/review/workflow.ts. Do not edit.\n${metadata}\n${output.outputFiles[0].text}\nreturn await ReviewWorkflow.runReviewWorkflow(args);\n`;
if (Buffer.byteLength(source) > 512 * 1024) {
  throw new Error("Workflow exceeds the pi-subagents script limit");
}
const path = `${root}/workflows/review.js`;
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== source) {
    throw new Error("Generated workflow is stale. Run npm run build.");
  }
} else {
  await writeFile(path, source);
}
